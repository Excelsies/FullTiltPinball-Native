#!/usr/bin/env python
"""Output side of control_tables.py: the readable control_tables.md and the annotated handler
listings (Ghidra export bodies with component tags, handler names and string resources named).
Not run directly; used by control_tables.py.
"""
import json
import os
import re
import struct

import pefile


def annotate(img, export_c, handlers, out_path):
    """Write the handlers' decompiled bodies from the Ghidra export with tag globals renamed
    (DAT_<tag+4> -> <name>.component) and handler functions named."""
    blocks = re.split(r"^(// ==== ([0-9a-f]{8}) \S+ size \d+)$", open(export_c).read(), flags=re.M)
    bodies = {int(blocks[i + 1], 16): blocks[i] + blocks[i + 2] for i in range(1, len(blocks), 3)}
    names = {r["addr"]: (r.get("upstream_name") if r["class"] in ("reference", "identical")
                         else None) or r["proposed_name"] for r in handlers}

    def sym(m):
        v = int(m.group(1), 16)
        if v in img.all_tags:
            return f"&tag[{img.all_tags[v]}]"
        if v - 4 in img.all_tags:
            return f"{img.all_tags[v - 4]}.component"
        if m.group(0).startswith("FUN_") and v in names:
            return f"{names[v]}_{v:x}"
        return m.group(0)

    strings = rc_strings(img.path)
    getter = [a for a, b in bodies.items() if "LoadStringA(" in b and "(short param_1)" in b]

    def rc(m):
        sid = int(m.group(2), 16)
        return f"{m.group(1)}{m.group(2)} /* {json.dumps(strings.get(sid, '?'))} */)"

    with open(out_path, "w") as f:
        f.write(f"// {os.path.basename(img.path)} score_components handlers, from the Ghidra export;"
                f" tags resolved by re/control_tables.py. Decompiled material: do not commit.\n")
        for r in handlers:
            f.write(f"\n// handler {r['addr']:#x} [{r['class']}] {names[r['addr']]} for "
                    f"{', '.join(r['entry_tags'])}\n")
            body = bodies.get(r["addr"], "// (not in export)\n")
            for g in getter:  # string resource ids -> text
                body = re.sub(rf"(FUN_{g:08x}\()(0x[0-9a-f]+)\)", rc, body)
            f.write(re.sub(r"\b_?(?:PTR_PTR_|PTR_DAT_|PTR_|DAT_|FUN_)([0-9a-f]{8})\b", sym, body))


def rc_strings(path):
    """{string id: text} from the exe's RT_STRING resources (16 strings per block)."""
    pe = pefile.PE(path)
    out = {}
    for typ in getattr(pe, "DIRECTORY_ENTRY_RESOURCE", None).entries:
        if typ.id != 6:
            continue
        for block in typ.directory.entries:
            for lang in block.directory.entries:
                data = pe.get_data(lang.data.struct.OffsetToData, lang.data.struct.Size)
                pos = 0
                for i in range(16):
                    n = struct.unpack_from("<H", data, pos)[0]
                    pos += 2
                    if n:
                        out[(block.id - 1) * 16 + i] = data[pos:pos + 2 * n].decode("utf-16-le")
                    pos += 2 * n
    return out


def h(v):
    return f"{v:#x}" if isinstance(v, int) else ("" if v is None else str(v))


def markdown(results, ref_stem):
    L = ["# Full Tilt control tables (generated by re/control_tables.py)", "",
         "Decompiled-material derived: keep under re/work/ (gitignored).", ""]
    for stem, (img, d) in results.items():
        L += [f"## {d['exe']}", "",
              f"- make_links {h(d['make_links'])}, make_component_link {h(d['make_component_link'])}, "
              f"TableG {h(d['table_global'])}",
              f"- score_components {h(d['score_components']['addr'])} x{d['score_components']['count']} "
              f"(16 bytes), simple_components {h(d['simple_components']['addr'])} "
              f"x{d['simple_components']['count']}",
              f"- tags: {len(d['tags'])} ({sum(not t['listed'] for t in d['tags'])} not in either array)",
              f"- distinct handlers: {len(d['handlers'])}"]
        by_cls = {}
        for t in d["tags"]:
            by_cls[t["part_class"] or "?"] = by_cls.get(t["part_class"] or "?", 0) + 1
        L.append("- tags by .DAT part class: " +
                 ", ".join(f"{k} {v}" for k, v in sorted(by_cls.items(), key=lambda kv: -kv[1])))
        if stem == ref_stem:
            L.append("- verification against control.cpp (tag names, score counts, score values, "
                     "handler identity, classifier self-check): " +
                     ("OK, no mismatches" if not d["verification_problems"] else
                      "; ".join(d["verification_problems"])))
            L += [f"- note: {n}" for n in d.get("verification_notes", [])]
        else:
            counts = {}
            for r in d["handlers"]:
                counts[r["class"]] = counts.get(r["class"], 0) + 1
            L.append(f"- handler classes vs {ref_stem}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
        hn = {r["addr"]: r for r in d["handlers"]}
        L += ["", "### score_components", "",
              "| # | tag | type | handler | name | n | scores |", "|---|---|---|---|---|---|---|"]
        for e in d["score_entries"]:
            r = hn[e["handler"]]
            name = r.get("upstream_name") or ""
            if stem != ref_stem:
                name = f"{r['class']}" + (f": {name}" if name else "")
                if r["class"] in ("new", "similar", "same-code"):
                    name += f" -> {r['proposed_name']}"
            sc = ",".join(map(str, e["scores"]))
            if e.get("upstream_scores_var"):
                sc += f" ({e['upstream_scores_var']})"
            L.append(f"| {e['index']} | {e['tag']} | {e.get('part_class') or ''} | {h(e['handler'])} | "
                     f"{name} | {e['count']} | {sc} |")
        L += ["", "### simple_components", "",
              ", ".join(f"{e['tag']}" + (f" ({e['part_class']})" if e.get("part_class") else "")
                        for e in d["simple_entries"])]
        un = [t for t in d["tags"] if not t["listed"]]
        if un:
            L += ["", "Tags in neither array (used directly by rule code): " +
                  ", ".join(f"{t['name']} {h(t['addr'])}" for t in un)]
        if stem != ref_stem:
            by_class = {}
            for r in d["handlers"]:
                n, b = by_class.get(r["class"], (0, 0))
                by_class[r["class"]] = (n + 1, b + r["size"])
            L += ["", "### handler inventory", "",
                  "By class: " + ", ".join(f"{k} {n} ({b} bytes)" for k, (n, b) in sorted(by_class.items())),
                  "", "| handler | bytes | class | closest CADET (ratio) | upstream name | proposed name | "
                  "entry tags | note |", "|---|---|---|---|---|---|---|---|"]
            for r in d["handlers"]:
                up = r.get("upstream_name") or ""
                prop = "" if r["class"] == "identical" else r["proposed_name"]
                L.append(f"| {h(r['addr'])} | {r['size']} | {r['class']} | {h(r.get('match'))} "
                         f"({r.get('match_ratio', '')}) | {up} | {prop} | {', '.join(r['entry_tags'])} "
                         f"| {r['proposed_note']} |")
        L.append("")
    return "\n".join(L)
