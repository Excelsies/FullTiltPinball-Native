"""Generate the Wine rest-state watch files and native rest scripts for a Full Tilt table.

  python re/test/scripts/make_rest_watch.py <dragon|pirates> re/work/spec/control_tables_<t>.json
         [--out-dir re/test/scripts] [--uh-dir re/test/hook_scripts]

Writes ``rest_<t>.json`` (probe_run.py ``restpeek`` format: one value per control tag and field,
{"name": "<tag>.<field>", "tag": "0x..", "field": "0x..", "type": "i32|u8|f32|armed"}; ftpeek
reads tag+4 -> component -> +field) and ``rest_<t>.uh`` (native: dump the same file at frames 300,
350 and 400). Fields per part class are the native hook's dump fields that have a known Wine offset. Addresses and part names
only, no game data. Deterministic: a rerun gives identical files.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEST_DIR = HERE.parent

EVERY = [("active", 0x05, "u8"), ("message_field", 0x06, "i32")]
# class -> class-specific fields (the native hook's dump fields). Fields without a Wine offset are not listed.
CLASS_FIELDS = {
    "TLight": [("light_on", 0x42, "i32"), ("flasher_on", 0x46, "i32"), ("override", 0x5A, "i32")],
    "TBlocker": [("blocker_state", 0x7E, "i32")],
    "TPlunger": [("boost", 0x66, "f32"), ("max_pullback", 0x7A, "f32"),
                 ("pullback_started", 0x92, "i32")],
    "TRampExit": [("group_a", 0x82, "i32"), ("group_b", 0x7A, "i32")],
    "TAccelerator": [("speed_mult1", 0x8A, "f32"), ("speed_mult2", 0x8E, "f32"),
                     ("dir_x", 0x7A, "f32"), ("dir_y", 0x7E, "f32")],
    "TLightSweeps": [("columns", 0x5A, "i32"), ("rows", 0x5E, "i32"), ("xmin", 0x62, "f32"),
                     ("ymin", 0x66, "f32"), ("inv_cell_w", 0x52, "f32"), ("inv_cell_h", 0x56, "f32"),
                     ("radius", 0x82, "i32"), ("repeats_left", 0x7E, "i32"), ("timer", 0x8A, "armed")],
    "TDiverter": [("flash_time", 0x82, "f32")],
    "TMagnet": [("hold_off", 0x76, "i32"), ("field_mult", 0x92, "f32"), ("hold_off_time", 0x86, "f32")],
}
# control_tables_<t>.json names engine part types without a class by their DAT type id.
TYPE_CLASS = {"type1035": "TRampExit", "type1036": "TAccelerator", "type1038": "TLightSweeps",
              "type1042": "TMagnet", "type1043": "TDiverter"}
SCRIPT_FRAMES = (300, 350, 400)
QUIT_FRAME = 410


def base_class(part_class: str | None) -> str | None:
    """'TPlunger(flag 1)' -> 'TPlunger', 'type1043' -> 'TDiverter'; None when the class is unknown."""
    if not part_class or not isinstance(part_class, str) or part_class.startswith("?"):
        return None
    name = re.sub(r"\s*\(.*\)$", "", part_class).strip()
    name = name.split(" ")[0]
    if name.startswith("type"):
        return TYPE_CLASS.get(name)
    return name


def build(tables: dict, table: str) -> tuple[dict, list[str], list[str]]:
    seen: dict[str, int] = {}
    values, unknown, renamed = [], [], []
    for tag in tables["tags"]:
        cls = base_class(tag.get("part_class"))
        if cls is None:
            unknown.append(f"{tag['name']} ({tag.get('part_class')!r})")
        fields = EVERY + CLASS_FIELDS.get(cls, [])
        name = tag["name"]
        seen[name] = seen.get(name, 0) + 1
        if seen[name] > 1:                       # duplicate group name: keep both, distinguishably
            name = f"{name}@{tag['addr']:x}"
            renamed.append(name)
        for field, off, typ in fields:
            values.append({"name": f"{name}.{field}", "tag": f"0x{tag['addr']:x}",
                           "field": f"0x{off:x}", "type": typ})
    names = [v["name"] for v in values]
    assert len(names) == len(set(names)), "duplicate rest keys"
    watch = {"_comment": f"Rest-state reads for {tables['exe']}; generated by "
                         f"re/test/scripts/make_rest_watch.py from control_tables_{table}.json "
                         "(addresses and part names only).",
             "table_global": f"0x{tables['table_global']:x}", "values": values}
    return watch, unknown, renamed


def uh_text(table: str) -> str:
    rest = f"re/test/scripts/rest_{table}.json"
    lines = ["init window 960 666", "init fixed_dt 10"]
    lines += [f"{f} dump rest_{i} @{rest}" for i, f in enumerate(SCRIPT_FRAMES, 1)]
    lines.append(f"{QUIT_FRAME} quit")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("table", choices=("dragon", "pirates"))
    ap.add_argument("control_tables")
    ap.add_argument("--out-dir", default=str(HERE))
    ap.add_argument("--uh-dir", default=str(TEST_DIR / "hook_scripts"))
    args = ap.parse_args(argv)
    try:
        tables = json.loads(Path(args.control_tables).read_text(encoding="utf-8"))
        watch, unknown, renamed = build(tables, args.table)
    except (OSError, ValueError, KeyError) as exc:
        print(f"make_rest_watch: {exc}", file=sys.stderr)
        return 2
    out, uh = Path(args.out_dir), Path(args.uh_dir)
    out.mkdir(parents=True, exist_ok=True)
    uh.mkdir(parents=True, exist_ok=True)
    (out / f"rest_{args.table}.json").write_text(json.dumps(watch, indent=1) + "\n", encoding="utf-8")
    (uh / f"rest_{args.table}.uh").write_text(uh_text(args.table), encoding="utf-8")
    if unknown:
        print(f"unknown part class ({len(unknown)}): {', '.join(unknown)}", file=sys.stderr)
    if renamed:
        print(f"duplicate tag names renamed: {', '.join(renamed)}", file=sys.stderr)
    print(f"{args.table}: {len(tables['tags'])} tags, {len(watch['values'])} keys")
    return 0


if __name__ == "__main__":
    sys.exit(main())
